"""Таблица растворимости (катион × анион) — школьный курс, без органики.

Значения: 'Р' — растворим, 'М' — малорастворим, 'Н' — нерастворим,
'-' — вещество не существует / разлагается водой (гидролиз) и в игре не
используется ни как реагент, ни как продукт.

H⁺ как катион (кислоты) и пара H⁺/OH⁻ (вода) в таблицу солей не входят —
обрабатываются отдельно в `reactions.py`.
"""

from __future__ import annotations

from typing import Literal

Solub = Literal["Р", "М", "Н", "-"]

# Порядок анионов в строках таблицы.
_ANIONS = ["OH", "F", "Cl", "Br", "I", "S", "SO3", "SO4",
           "NO3", "NO2", "CO3", "SiO3", "PO4"]

# Катионы солей (без H⁺).
_SALT_CATIONS = ["NH4", "K", "Na", "Ag", "Ba", "Ca", "Mg",
                 "Al", "Zn", "Fe", "Ni", "Pb", "Cu"]

# Канонические значения (строка на катион, порядок столбцов = _ANIONS).
#                OH   F    Cl   Br   I    S    SO3  SO4  NO3  NO2  CO3  SiO3 PO4
_ROWS = {
    "NH4": ["Р", "Р", "Р", "Р", "Р", "Р", "Р", "Р", "Р", "Р", "Р", "Р", "Р"],
    "K":   ["Р", "Р", "Р", "Р", "Р", "Р", "Р", "Р", "Р", "Р", "Р", "Р", "Р"],
    "Na":  ["Р", "Р", "Р", "Р", "Р", "Р", "Р", "Р", "Р", "Р", "Р", "Р", "Р"],
    "Ag":  ["Н", "Р", "Н", "Н", "Н", "Н", "Н", "М", "Р", "М", "Н", "Н", "Н"],
    "Ba":  ["Р", "М", "Р", "Р", "Р", "-", "Н", "Н", "Р", "Р", "Н", "Н", "Н"],
    "Ca":  ["М", "Н", "Р", "Р", "Р", "-", "Н", "М", "Р", "Р", "Н", "Н", "Н"],
    "Mg":  ["Н", "Н", "Р", "Р", "Р", "-", "Н", "Р", "Р", "Р", "Н", "Н", "Н"],
    "Al":  ["Н", "Р", "Р", "Р", "Р", "-", "-", "Р", "Р", "-", "-", "-", "Н"],
    "Zn":  ["Н", "Р", "Р", "Р", "Р", "Н", "Н", "Р", "Р", "Р", "Н", "Н", "Н"],
    "Fe":  ["Н", "Р", "Р", "Р", "Р", "Н", "Н", "Р", "Р", "Р", "Н", "Н", "Н"],
    "Ni":  ["Н", "Р", "Р", "Р", "Р", "Н", "Н", "Р", "Р", "Р", "Н", "Н", "Н"],
    "Pb":  ["Н", "Н", "М", "М", "Н", "Н", "Н", "Н", "Р", "Р", "Н", "Н", "Н"],
    "Cu":  ["Н", "Р", "Р", "Р", "-", "Н", "Н", "Р", "Р", "Р", "Н", "Н", "Н"],
}

_TABLE: dict[str, dict[str, Solub]] = {
    cat: dict(zip(_ANIONS, row)) for cat, row in _ROWS.items()
}

SALT_CATIONS = tuple(_SALT_CATIONS)
ANIONS = tuple(_ANIONS)


def solubility(cation_key: str, anion_key: str) -> Solub:
    """Растворимость соли катион+анион ('Р'/'М'/'Н'/'-').

    '-' означает «не существует / гидролизуется». KeyError — для пары вне набора.
    """
    return _TABLE[cation_key][anion_key]


def exists(cation_key: str, anion_key: str) -> bool:
    """True, если соединение существует (значение в таблице не '-')."""
    return _TABLE[cation_key][anion_key] != "-"
