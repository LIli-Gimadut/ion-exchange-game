# Запасной цвет по катиону, если пары нет в таблице.
_FALLBACK_COLOR = {
    "Cu": "голубой", "Ni": "зелёный", "Fe": "зеленоватый", "Ag": "жёлтый",
}


def _fallback(cation_key: str, anion_key: str) -> tuple[str, str]:
    color = _FALLBACK_COLOR.get(cation_key, "белый")
    if anion_key == "OH":
        texture = "студенистый"
    elif anion_key == "S":
        texture = "аморфный"
    elif anion_key in ("CO3", "SO4", "SO3", "F"):
        texture = "кристаллический"
    else:
        texture = "аморфный"
    return color, texture


def _star_product(result: ReactionResult, state: str) -> Product | None:
    for p in result.products:
        if p.state == state and p.formula == result.star_formula:
            return p
    for p in result.products:
        if p.state == state:
            return p
    return None


# Яркие (утрированные) цвета осадков для анимации, по названию цвета.
_COLOR_RGB = {
    "белый": (245, 245, 250),
    "жёлтый": (250, 214, 64),
    "бледно-жёлтый": (244, 231, 148),
    "светло-зелёный": (150, 222, 150),
    "зелёный": (58, 200, 110),
    "зеленоватый": (150, 205, 158),
    "голубой": (74, 168, 236),
    "бурый": (156, 86, 44),
    "чёрный": (44, 44, 54),
}


def _precip_name(p: Product) -> str:
    return _PRECIP.get(
        (p.cation.key, p.anion.key), _fallback(p.cation.key, p.anion.key)
    )[0]


def precipitate_is_colored(result: ReactionResult) -> bool:
    """True, если в реакции образуется цветной (не белый) осадок."""
    p = _star_product(result, "precipitate")
    return p is not None and _precip_name(p) != "белый"


def precipitate_color(result: ReactionResult) -> tuple[int, int, int, int]:
    """Яркий цвет осадка для анимации (совпадает с реальным цветом продукта)."""
    p = _star_product(result, "precipitate")
    if p is None:
        return (230, 230, 236, 235)
    r, g, b = _COLOR_RGB.get(_precip_name(p), (230, 230, 236))
    return (r, g, b, 235)


def _fragment(p: Product) -> tuple[str, str] | None:
    """(глагол, описание) для одного видимого продукта, либо None."""
    if p.state == "gas":
        color, smell = _GAS.get(p.formula, ("бесцветный", "без запаха"))
        return ("Выделился", f"{color} газ {smell}")
    if p.state == "precipitate":
        color, texture = _PRECIP.get(
            (p.cation.key, p.anion.key), _fallback(p.cation.key, p.anion.key)
        )
        return ("Образовался", f"{color} {texture} осадок")
    if p.state == "water":
        return ("Образовалась", "вода")
    return None


def describe_result(result: ReactionResult) -> str:
    """Русское предложение о наблюдаемом: каждый осадок и каждый газ по порядку.

    Если продукт один — обычное предложение. Если несколько с одним глаголом
    (напр. два осадка) — «Образовался … и …». Если глаголы разные (осадок + вода) —
    клаузы через запятую.
    """
    parts = [f for p in result.products if (f := _fragment(p)) is not None]
    if not parts:
        return "Реакция прошла."
    if len({verb for verb, _ in parts}) == 1:
        verb = parts[0][0]
        return verb + " " + " и ".join(desc for _, desc in parts) + "."
    clauses = [
        f"{verb} {desc}" if i == 0 else f"{verb.lower()} {desc}"
        for i, (verb, desc) in enumerate(parts)
    ]
    return ", ".join(clauses) + "."
